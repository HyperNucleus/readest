// 复用上游 Compose 服务定义，生成独立项目的运行配置及单域名 Nginx 配置。
import { createHmac, randomBytes } from 'node:crypto';
import { mkdir, writeFile, copyFile, readdir } from 'node:fs/promises';
import path from 'node:path';
import { ROOT, STATE, clientProfile, loadJson, saveJson, serverDirectories } from './config.mjs';
import { run, prepareSources } from './process.mjs';

export const SERVER_FILE = path.join(STATE, 'server.json');
export const COMPOSE_FILE = path.join(STATE, 'compose.json');

// 新部署只生成一次；重新配置/升级必须保留 JWT 和存储凭据，以免旧客户端失效。
export function newSecrets() {
  const secret = () => randomBytes(32).toString('hex');
  const jwtSecret = secret();
  const token = (role) => {
    const encode = (v) => Buffer.from(JSON.stringify(v)).toString('base64url');
    const body = `${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ role, iss: 'supabase', iat: Math.floor(Date.now() / 1000) })}`;
    return `${body}.${createHmac('sha256', jwtSecret).update(body).digest('base64url')}`;
  };
  return { jwtSecret, postgresPassword: secret(), minioPassword: secret(), anonKey: token('anon'), serviceRoleKey: token('service_role') };
}

// 只把服务器需要的环境注入 Compose，所有服务保持关闭公开注册和邮件登录链接。
function serverEnvironment(s) {
  return {
    HOST_IP: new URL(s.serverUrl).hostname, SITE_URL: s.serverUrl, API_EXTERNAL_URL: s.serverUrl,
    SUPABASE_PUBLIC_URL: s.serverUrl, S3_PUBLIC_ENDPOINT: s.serverUrl,
    POSTGRES_PASSWORD: s.secrets.postgresPassword, POSTGRES_HOST: 'db', POSTGRES_PORT: '5432', POSTGRES_DB: 'postgres',
    JWT_SECRET: s.secrets.jwtSecret, JWT_EXPIRY: '3600', ANON_KEY: s.secrets.anonKey, SERVICE_ROLE_KEY: s.secrets.serviceRoleKey,
    KONG_HTTP_PORT: String(s.ports.kong), ADDITIONAL_REDIRECT_URLS: `${s.serverUrl}/auth/**,${s.scheme}://auth-callback`,
    DISABLE_SIGNUP: 'true', ENABLE_EMAIL_SIGNUP: 'true', ENABLE_EMAIL_AUTOCONFIRM: 'true', ENABLE_ANONYMOUS_USERS: 'false',
    SMTP_HOST: '', SMTP_PORT: '587', SMTP_USER: '', SMTP_PASS: '', SMTP_ADMIN_EMAIL: '', SMTP_SENDER_NAME: s.appName,
    PGRST_DB_SCHEMAS: 'public,graphql_public', MINIO_ROOT_USER: 'readest-admin', MINIO_ROOT_PASSWORD: s.secrets.minioPassword,
    S3_BUCKET_NAME: 'readest-files', OBJECT_STORAGE_TYPE: 's3', SELF_HOSTED: 'true',
    STORAGE_FIXED_QUOTA: String(s.storageQuota), TRANSLATION_FIXED_QUOTA: String(s.translationQuota),
    FONT_BASE_URL: s.fontBaseUrl, READEST_TRUSTED_PRIVATE_HOSTS: s.trustedHosts,
    READEST_IMAGE: 'readest-selfhost:local',
  };
}

// Nginx 由用户安装到宿主机；保留 MinIO Host，确保预签名下载 URL 验签通过。
export function nginxConfig(s) {
  const domain = new URL(s.serverUrl).hostname;
  return `# Generated by pnpm selfhost: install certificates before enabling this site.
server {
  listen 80;
  server_name ${domain};
  return 301 https://$host$request_uri;
}
server {
  listen 443 ssl;
  server_name ${domain};
  ssl_certificate ${s.certificate};
  ssl_certificate_key ${s.certificateKey};
  location / {
    proxy_pass http://127.0.0.1:${s.ports.client};
    proxy_set_header Host $http_host;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
  }
  location ~ ^/(auth|rest)/v1/ {
    proxy_pass http://127.0.0.1:${s.ports.kong};
    proxy_set_header Host $http_host;
    proxy_set_header X-Forwarded-Proto $scheme;
  }
  location /readest-files/ {
    proxy_pass http://127.0.0.1:${s.ports.s3};
    proxy_set_header Host $http_host;
    client_max_body_size 0;
    proxy_request_buffering off;
  }
  # Only published artifacts are public; staging and private configuration live elsewhere.
  location /updates/ {
    alias ${s.dataDir}/updates/;
    autoindex off;
    add_header Cache-Control "no-cache";
  }
}
`;
}

// 配置导出解析交给 Docker Compose，避免复制整份上游服务定义而遗漏迁移挂载。
export async function generateServer(s) {
  if (process.platform !== 'linux') throw new Error('服务端配置生成/部署需要在 Linux 服务器执行');
  // 部署和恢复也检查已保存路径，不能绕过向导把运行文件写进源码或密钥目录。
  serverDirectories(s.dataDir, s.backupDir);
  await mkdir(STATE, { recursive: true, mode: 0o700 });
  const empty = path.join(STATE, 'empty.env');
  await writeFile(empty, '', { mode: 0o600 });
  const resolved = await run('docker', ['compose', '--env-file', empty, '-f', path.join(ROOT, 'docker/compose.yaml'), 'config', '--format', 'json'], { env: serverEnvironment(s), capture: true });
  const compose = JSON.parse(resolved);
  // 官方 MinIO 镜像已不可拉取；使用用户确认的 Coollabs 修复版，并固定摘要防止标签漂移。
  // 同一镜像内含 mc，初始化服务继续使用上游的 /bin/sh 与 mc 建桶命令。
  const minioImage = 'coollabsio/minio:RELEASE.2025-10-15T17-29-55Z@sha256:69b55a1c1c5dc285ce04db96689f5b2102317fc77a50680a1874ca6efd1c87f9';
  compose.services.minio.image = minioImage;
  compose.services['minio-setup'].image = minioImage;
  compose.name = 'readest-selfhost';
  for (const [name, service] of Object.entries(compose.services)) {
    if (service.container_name) service.container_name = `readest-selfhost-${name}`;
    delete service.ports;
  }
  // 只有本机反向代理可访问 API/文件服务，不向公网暴露数据库和 MinIO 管理控制台。
  for (const [name, target, port] of [['client', 3000, s.ports.client], ['kong', 8000, s.ports.kong], ['minio', 9000, s.ports.s3]]) {
    compose.services[name].ports = [{ target, published: String(port), host_ip: '127.0.0.1', protocol: 'tcp' }];
  }
  const bindVolume = (name, target, directory) => {
    compose.services[name].volumes = compose.services[name].volumes.filter((v) => v.target !== target);
    compose.services[name].volumes.push({ type: 'bind', source: path.join(s.dataDir, directory), target });
  };
  bindVolume('db', '/var/lib/postgresql/data', 'postgres');
  bindVolume('db', '/etc/postgresql-custom', 'postgres-config');
  // bind mount 不像命名卷那样自动复制镜像内容；先补齐默认配置，且不覆盖已有配置。
  compose.services['db-config-init'] = {
    image: compose.services.db.image,
    user: '0:0',
    entrypoint: ['/bin/sh', '-c'],
    command: ['cp -an /etc/postgresql-custom/. /readest-postgres-config/'],
    volumes: [{ type: 'bind', source: path.join(s.dataDir, 'postgres-config'), target: '/readest-postgres-config' }],
    restart: 'no',
  };
  compose.services.db.depends_on = { 'db-config-init': { condition: 'service_completed_successfully' } };
  bindVolume('minio', '/data', 'objects');
  delete compose.volumes;
  // 源码构建本分支，不能悄悄拉取官方镜像覆盖自定义功能。
  compose.services.client.build = { context: ROOT, target: 'production-stage', args: {
    NEXT_PUBLIC_APP_PLATFORM: 'web', NEXT_PUBLIC_PERSONAL: 'true', NEXT_PUBLIC_API_BASE_URL: s.serverUrl,
    NEXT_PUBLIC_UPDATER_BASE_URL: `${s.serverUrl}/updates`, NEXT_PUBLIC_APP_SCHEME: s.scheme,
  } };
  compose.services.client.pull_policy = 'never';
  compose.services.client.environment.NODE_BASE_URL = s.serverUrl;
  compose.services.client.environment.READEST_PERSONAL = 'true';
  // 数据库就绪后才启动认证/REST，MinIO 建桶成功后才开放网页，避免首次启动竞态。
  compose.services.db.healthcheck = { test: ['CMD-SHELL', 'pg_isready -U supabase_admin -h 127.0.0.1'], interval: '5s', timeout: '5s', retries: 30 };
  for (const name of ['auth', 'rest']) compose.services[name].depends_on = { db: { condition: 'service_healthy' } };
  compose.services.kong.depends_on = { auth: { condition: 'service_started' }, rest: { condition: 'service_started' } };
  compose.services.client.depends_on['minio-setup'] = { condition: 'service_completed_successfully' };
  await saveJson(COMPOSE_FILE, compose);
  await writeFile(path.join(STATE, 'nginx.conf'), nginxConfig(s), { mode: 0o600 });
}

// 所有操作固定到生成的独立项目，避免影响机器上的其他 Compose 项目。
export const composeRun = (args, options) => run('docker', ['compose', '-p', 'readest-selfhost', '-f', COMPOSE_FILE, ...args], options);

export async function deploy(s) {
  await generateServer(s);
  for (const directory of ['postgres', 'postgres-config', 'objects', 'updates']) {
    await mkdir(path.join(s.dataDir, directory), { recursive: true });
  }
  await prepareSources();
  await composeRun(['build', 'client']);
  await composeRun(['up', '-d', '--wait', '--wait-timeout', '180']);
  // 既有数据库也需要执行增量迁移；不能只依赖首次启动钩子。
  await composeRun(['exec', '-T', 'db', '/docker-entrypoint-initdb.d/zz-readest-migrations.sh']);
}

// 通过本机 Kong 调用管理员 API，创建/重置账号无需开放注册或配置 SMTP。
export async function account(s, email, password, reset = false) {
  const base = `http://127.0.0.1:${s.ports.kong}/auth/v1/admin/users`;
  const headers = { apikey: s.secrets.serviceRoleKey, Authorization: `Bearer ${s.secrets.serviceRoleKey}`, 'Content-Type': 'application/json' };
  let endpoint = base;
  if (reset) {
    let user;
    for (let page = 1; ; page++) {
      const response = await fetch(`${base}?page=${page}&per_page=100`, { headers, signal: AbortSignal.timeout(15000) });
      if (!response.ok) throw new Error(`读取账号失败（${response.status}）`);
      const result = await response.json();
      const users = result.users ?? [];
      user = users.find((u) => u.email?.toLowerCase() === email.toLowerCase());
      if (user || users.length < 100) break;
    }
    if (!user) throw new Error('未找到该邮箱账号');
    endpoint = `${base}/${encodeURIComponent(user.id)}`;
  }
  const response = await fetch(endpoint, { method: reset ? 'PUT' : 'POST', headers,
    body: JSON.stringify({ email, password, email_confirm: true }), signal: AbortSignal.timeout(15000) });
  if (!response.ok) throw new Error(`账号操作失败（HTTP ${response.status}），请检查服务日志`);
}

// 停止整个栈再做物理备份，数据库与对象文件保持同一时间点；恢复使用备份镜像版本。
export async function backup(s) {
  const directory = path.join(s.backupDir, new Date().toISOString().replaceAll(':', '-'));
  await mkdir(directory, { recursive: true, mode: 0o700 });
  const running = (await composeRun(['ps', '--services', '--status', 'running'], { capture: true })).split('\n').filter(Boolean);
  // 记录镜像 ID，避免恢复时把旧 PostgreSQL 数据交给不同版本的镜像。
  const config = await loadJson(COMPOSE_FILE);
  const imageList = {};
  for (const [name, service] of Object.entries(config.services)) {
    const images = JSON.parse(await run('docker', ['image', 'inspect', service.image], { capture: true }));
    imageList[name] = images[0].Id;
    // 上游服务用可重新拉取的 digest 固定版本；本地网页镜像另行打包带走。
    if (name !== 'client') service.image = images[0].RepoDigests?.[0] || service.image;
  }
  await saveJson(path.join(directory, 'images.json'), imageList);
  await run('docker', ['image', 'save', '-o', path.join(directory, 'client-image.tar'), config.services.client.image]);
  await composeRun(['stop']);
  try {
    await copyFile(SERVER_FILE, path.join(directory, 'server.json'));
    await saveJson(path.join(directory, 'compose.json'), config);
    // 备份含凭据，限制宿主机权限；容器仅挂载数据与本次备份目录。
    await run('docker', ['run', '--rm', '-v', `${s.dataDir}:/data:ro`, '-v', `${directory}:/backup`, 'alpine:3.22',
      'sh', '-c', `tar czpf /backup/data.tar.gz -C /data . && chown ${process.getuid()}:${process.getgid()} /backup/data.tar.gz && chmod 600 /backup/data.tar.gz`]);
    await saveJson(path.join(directory, 'manifest.json'), { version: 1, createdAt: new Date().toISOString(), platform: process.arch,
      commit: await run('git', ['rev-parse', 'HEAD'], { capture: true }) });
  } finally {
    if (running.length) await composeRun(['start', ...running]);
  }
  console.log(`备份完成（含服务端密钥，请妥善保管）：${directory}`);
  return directory;
}

// 恢复只允许空数据目录，绝不清空现有书库；用户须先停止旧实例并选择新目录。
export async function restore(directory, target, backupDirectory = path.join(STATE, 'backups')) {
  // 迁移到另一处项目时重新定位备份目录，不沿用旧服务器仓库的绝对路径。
  const destinations = serverDirectories(target, backupDirectory);
  const manifest = await loadJson(path.join(directory, 'manifest.json'));
  if (manifest.version !== 1 || manifest.platform !== process.arch) throw new Error('物理备份版本/CPU 架构不兼容');
  await mkdir(target, { recursive: true });
  if ((await readdir(target)).length) throw new Error('恢复目标必须是空目录');
  const server = await loadJson(path.join(directory, 'server.json'));
  Object.assign(server, destinations);
  await run('docker', ['run', '--rm', '-v', `${target}:/data`, '-v', `${directory}:/backup:ro`, 'alpine:3.22', 'tar', 'xzpf', '/backup/data.tar.gz', '-C', '/data']);
  await saveJson(SERVER_FILE, server);
  // 恢复公开连接配置，使新服务器可继续验证后续 SSH 上传的安装包。
  await saveJson(path.join(STATE, 'client.json'), clientProfile({ ...server, supabaseAnonKey: server.secrets.anonKey }));
  await generateServer(server);
  // 保留备份时使用的镜像标签；恢复后由用户单独选择启动/更新，不隐式升级数据库。
  const old = await loadJson(path.join(directory, 'compose.json'));
  const current = await loadJson(COMPOSE_FILE);
  for (const [name, service] of Object.entries(old.services)) {
    if (current.services[name] && name !== 'client') current.services[name].image = service.image;
  }
  await saveJson(COMPOSE_FILE, current);
  await run('docker', ['image', 'load', '-i', path.join(directory, 'client-image.tar')]);
  console.log(`数据已恢复。请核对镜像/代码版本 ${manifest.commit}、安装 Nginx 配置，再用“启动已恢复服务”启动；不要同时开放新旧实例写入。`);
}
